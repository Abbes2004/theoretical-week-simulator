"""Generate the large-scale SYNTHETIC Phase 2 benchmark dataset.

Usage (from the project root):

    python scripts/generate_benchmark_dataset.py --scale 100000
    python scripts/generate_benchmark_dataset.py --scale 500000
    python scripts/generate_benchmark_dataset.py --scale 1000000
    python scripts/generate_benchmark_dataset.py --scale 5000000 --confirm-large   # optional, NOT run by default

Writes partitioned Parquet under
data/synthetic/benchmark_scale_2025_2026/{input,component_events,canonical_reference}/scale_<N>/
plus data/synthetic/benchmark_scale_2025_2026/metadata/scale_<N>.json

Never touches data/raw/, the real data/canonical/ tree, or
data/synthetic/demo_2025_2026/.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from configs import settings
from src.ingestion.synthetic_benchmark_generator import generate_benchmark_dataset

_REQUIRED_SCALES = set(settings.BENCHMARK_SCALES)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--scale",
        type=int,
        required=True,
        help=f"Number of POIs to generate. Supported by default: {sorted(_REQUIRED_SCALES)}. "
        f"{settings.BENCHMARK_SCALE_XL:,} requires --confirm-large.",
    )
    parser.add_argument(
        "--confirm-large",
        action="store_true",
        help=f"Required to generate the optional {settings.BENCHMARK_SCALE_XL:,}-POI scale "
        "(large disk/time footprint; never runs implicitly).",
    )
    parser.add_argument("--seed", type=int, default=settings.BENCHMARK_SEED)
    parser.add_argument("--chunk-size", type=int, default=settings.BENCHMARK_CHUNK_SIZE)
    args = parser.parse_args()

    if args.scale == settings.BENCHMARK_SCALE_XL and not args.confirm_large:
        parser.error(
            f"--scale {settings.BENCHMARK_SCALE_XL:,} is the optional XL mode and requires "
            "--confirm-large (it is never generated by default)."
        )
    if args.scale not in _REQUIRED_SCALES and args.scale != settings.BENCHMARK_SCALE_XL:
        print(
            f"WARNING: --scale {args.scale:,} is not one of the required scales "
            f"{sorted(_REQUIRED_SCALES)} or the optional XL scale "
            f"{settings.BENCHMARK_SCALE_XL:,}. Proceeding anyway (useful for quick manual tests).",
            file=sys.stderr,
        )

    scale_dir_name = f"scale_{args.scale}"
    input_dir = settings.BENCHMARK_SCALE_INPUT_DIR / scale_dir_name
    events_dir = settings.BENCHMARK_SCALE_EVENTS_DIR / scale_dir_name
    reference_dir = settings.BENCHMARK_SCALE_REFERENCE_DIR / scale_dir_name
    settings.BENCHMARK_SCALE_METADATA_DIR.mkdir(parents=True, exist_ok=True)

    print(f"Generating {args.scale:,} SYNTHETIC POIs (seed={args.seed}, "
          f"chunk_size={args.chunk_size:,}) -> {scale_dir_name}/")
    t0 = time.time()
    metadata = generate_benchmark_dataset(
        args.scale,
        seed=args.seed,
        chunk_size=args.chunk_size,
        input_dir=input_dir,
        events_dir=events_dir,
        reference_dir=reference_dir,
    )
    elapsed = time.time() - t0
    metadata["generation_wall_clock_seconds"] = round(elapsed, 3)
    metadata["generated_at_utc"] = datetime.now(timezone.utc).isoformat()

    metadata_path = settings.BENCHMARK_SCALE_METADATA_DIR / f"{scale_dir_name}.json"
    metadata_path.write_text(json.dumps(metadata, indent=2, default=str), encoding="utf-8")

    print(f"\nDone in {elapsed:.1f}s: {metadata['total_poi_rows']:,} POIs, "
          f"{metadata['total_component_events']:,} component events, "
          f"{metadata['n_chunks']} partition(s).")
    print(f"Status distribution: {metadata['calculation_status_distribution']}")
    print(f"Blocking distribution: {metadata['blocking_element_distribution']}")
    print(f"-> {metadata_path}")


if __name__ == "__main__":
    main()
